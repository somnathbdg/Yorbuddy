// ========== KYC Submission ==========

export async function submitKyc(req: Request, res: Response, next: NextFunction): Promise<void> {
  try {
    const input = submitKycSchema.parse(req.body);
    const userId = req.user!.id;
    const supabase = getSupabase();

    assertOwnedKycPath(input.document_path, userId, 'document');
    assertOwnedKycPath(input.selfie_path, userId, 'selfie');

    // Verify each exact object exists without returning a URL to the applicant.
    const [documentCheck, selfieCheck] = await Promise.all([
      supabase.storage.from('kyc-documents').createSignedUrl(input.document_path, 30),
      supabase.storage.from('kyc-documents').createSignedUrl(input.selfie_path, 30),
    ]);
    if (documentCheck.error || selfieCheck.error) {
      throw BadRequest('Uploaded KYC files could not be verified.');
    }

    // Check for existing pending KYC
    const { data: existing, error: existingError } = await supabase
      .from('verifications')
      .select('id, status')
      .eq('user_id', userId)
      .eq('status', 'pending')
      .limit(1);

    if (existingError) throw existingError;
    if (existing?.length) {
      throw BadRequest('You already have a pending KYC submission. Please wait for review.');
    }

    // Existing DB columns are retained for backward compatibility; values now store private object paths.
    const { data: kyc, error } = await supabase
      .from('verifications')
      .insert({
        user_id: userId,
        doc_type: input.doc_type,
        doc_front_url: input.document_path,
        selfie_url: input.selfie_path,
        status: 'pending',
        submitted_at: new Date().toISOString(),
      })
      .select()
      .single();

    if (error) throw error;

    res.status(201).json({
      data: {
        id: kyc.id,
        status: kyc.status,
        doc_type: kyc.doc_type,
        submitted_at: kyc.submitted_at,
      },
      message: 'KYC submitted successfully. Pending admin review.',
    });
  } catch (err) {
    next(err);
  }
}

