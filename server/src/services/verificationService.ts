export async function getKycById(req: Request, res: Response, next: NextFunction): Promise<void> {
  try {
    const { id } = kycIdParamSchema.parse(req.params);
    const supabase = getSupabase();

    const { data: kyc, error } = await supabase
      .from('verifications')
      .select(`
        id,
        user_id,
        doc_type,
        doc_front_url,
        selfie_url,
        status,
        rejection_reason,
        submitted_at,
        reviewed_at,
        reviewed_by
      `)
      .eq('id', id)
      .single();

    if (error || !kyc) {
      throw NotFound('KYC record not found.');
    }

    // Get user details separately
    const { data: userRow } = await supabase
      .from('users')
      .select('id, full_name, email, phone, email_verified_at, phone_verified_at')
      .eq('id', kyc.user_id)
      .single();

    // Admin-only route: issue short-lived read links only for objects under this user's prefix.
    const signedUrlExpirySeconds = 60;
    const documentPath = String(kyc.doc_front_url || '');
    const selfiePath = String(kyc.selfie_url || '');
    const documentOwned = documentPath.startsWith(`${kyc.user_id}/`) && !documentPath.includes('..');
    const selfieOwned = selfiePath.startsWith(`${kyc.user_id}/`) && !selfiePath.includes('..');

    const [documentSigned, selfieSigned] = await Promise.all([
      documentOwned
        ? supabase.storage.from('kyc-documents').createSignedUrl(documentPath, signedUrlExpirySeconds)
        : Promise.resolve({ data: null, error: new Error('Invalid document object path') }),
      selfieOwned
        ? supabase.storage.from('kyc-documents').createSignedUrl(selfiePath, signedUrlExpirySeconds)
        : Promise.resolve({ data: null, error: new Error('Invalid selfie object path') }),
    ]);

    if (documentSigned.error || selfieSigned.error) {
      throw NotFound('KYC files are unavailable in private storage.');
    }

    const safeKyc = {
      id: kyc.id,
      user_id: kyc.user_id,
      doc_type: kyc.doc_type,
      document_signed_url: documentSigned.data?.signedUrl,
      selfie_signed_url: selfieSigned.data?.signedUrl,
      signed_url_expires_in: signedUrlExpirySeconds,
      status: kyc.status === 'verified' ? 'approved' : kyc.status,
      rejection_reason: kyc.rejection_reason,
      submitted_at: kyc.submitted_at,
      reviewed_at: kyc.reviewed_at,
      reviewed_by: kyc.reviewed_by,
      user: userRow ? {
        id: userRow.id,
        full_name: userRow.full_name,
        email: userRow.email,
        phone: userRow.phone,
        email_verified: !!userRow.email_verified_at,
        phone_verified: !!userRow.phone_verified_at,
      } : null,
    };

    res.status(200).json({
      data: safeKyc,
    });
  } catch (err) {
    next(err);
  }
}

export async function approveKyc(req: Request, res: Response, next: NextFunction): Promise<void> {
  try {
    const { id } = kycIdParamSchema.parse(req.params);
    const adminId = req.user!.id;
    const supabase = getSupabase();

    // Fetch the KYC record
    const { data: kyc, error: fetchError } = await supabase
      .from('verifications')
      .select('id, user_id, status')
      .eq('id', id)
      .single();

    if (fetchError || !kyc) {
      throw NotFound('KYC record not found.');
    }

    // Cannot approve own KYC
    if (kyc.user_id === adminId) {
      throw Forbidden('You cannot approve your own KYC submission.');
    }

    if (kyc.status !== 'pending') {
      throw BadRequest(`Cannot approve KYC with status '${kyc.status}'. Only pending KYC can be approved.`);
    }

    const { data: updated, error } = await supabase
      .from('verifications')
      .update({
        status: 'approved',
        reviewed_at: new Date().toISOString(),
        reviewed_by: adminId,
      })
      .eq('id', id)
      .select()
      .single();

    if (error) throw error;

    // If user has an existing buddy_profiles row, sync verification status
    // so they appear in verified buddy search (existing application convention)
    // Do NOT create a buddy_profiles row — user must complete "Become a Buddy" first
    const { data: existingBuddyProfile } = await supabase
      .from('buddy_profiles')
      .select('id')
      .eq('user_id', kyc.user_id)
      .single();

    if (existingBuddyProfile) {
      await supabase
        .from('buddy_profiles')
        .update({ verification_status: 'approved', is_verified: true })
        .eq('user_id', kyc.user_id);
    }

    res.status(200).json({
      data: {
        id: updated.id,
        status: updated.status,
        reviewed_at: updated.reviewed_at,
        reviewed_by: updated.reviewed_by,
      },
      message: 'KYC approved successfully.',
    });
  } catch (err) {
    next(err);
  }
}

