const submitKycSchema = z.object({
  doc_type: z.enum(['pan', 'driving_license', 'voter_id']),
  document_path: z.string().min(1).max(500),
  selfie_path: z.string().min(1).max(500),
}).strict();

function assertOwnedKycPath(path: string, userId: string, kind: 'document' | 'selfie'): void {
  // Only accept the exact object key format generated by the upload endpoint.
  const uuid = '[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}';
  const extensions = kind === 'document' ? '(jpg|png|pdf)' : '(jpg|png)';
  const pattern = '^' + userId + '/' + uuid + '/' + kind + '\\.' + extensions + '$';
  if (!new RegExp(pattern, 'i').test(path)) throw Forbidden('Invalid KYC file reference.');
}

const rejectKycSchema = z.object({
  reason: z.string().min(10, 'Rejection reason must be at least 10 characters').max(500),
}).strict();

const kycIdParamSchema = z.object({
  id: z.string().uuid('Invalid KYC ID format'),
});

// ========== Database-Backed Verification Code Store ==========
// Codes are stored hashed in the database with expiration and one-time-use behavior.

function generateCode(): string {
  return crypto.randomInt(100000, 999999).toString();
}

function hashCode(code: string): string {
  return crypto.createHash('sha256').update(code).digest('hex');
}

async function storeCode(supabase: any, key: string, code: string, ttlMs: number = 10 * 60 * 1000): Promise<void> {
  const codeHash = hashCode(code);
  const expiresAt = new Date(Date.now() + ttlMs).toISOString();
  
  // Store hashed code in database
  await supabase.from('verification_codes').insert({
    key: key,
    code_hash: codeHash,
    expires_at: expiresAt,
    used_at: null,
  });
}

async function verifyCode(supabase: any, key: string, providedCode: string): Promise<boolean> {
  const codeHash = hashCode(providedCode);
  
  const { data: records, error } = await supabase
    .from('verification_codes')
    .select('*')
    .eq('key', key)
    .eq('code_hash', codeHash)
    .is('used_at', null)
    .order('created_at', { ascending: false })
    .limit(1);
  
  if (error || !records || records.length === 0) return false;
  
  const record = records[0];
  
  // Check expiration
  if (new Date(record.expires_at) < new Date()) {
    return false;
  }
  
  // Atomically consume the code so concurrent verification requests cannot
  // both succeed with the same one-time code.
  const { data: consumed, error: consumeError } = await supabase
    .from('verification_codes')
    .update({ used_at: new Date().toISOString() })
    .eq('id', record.id)
    .is('used_at', null)
    .select('id')
    .maybeSingle();

  if (consumeError || !consumed) return false;
  return true;
}

// ========== Helper: Get user verification status ==========

async function getUserVerificationStatus(supabase: any, userId: string): Promise<VerificationStatus> {
  const { data: user, error } = await supabase
    .from('users')
    .select('email_verified_at, phone_verified_at')
    .eq('id', userId)
    .single();

  if (error || !user) {
    throw NotFound('User not found.');
  }

  // Get latest KYC status
  const { data: kycRows } = await supabase
    .from('verifications')
    .select('status, rejection_reason')
    .eq('user_id', userId)
    .order('submitted_at', { ascending: false, nullsLast: true })
    .limit(1);

  let kyc: VerificationStatus['kyc'] = 'not_submitted';
  let kycRejectionReason: string | undefined;

  if (kycRows && kycRows.length > 0) {
    // Map 'verified' to 'approved' for compatibility
    const rawStatus = kycRows[0].status;
    kyc = rawStatus === 'verified' ? 'approved' : rawStatus as VerificationStatus['kyc'];
    kycRejectionReason = kycRows[0].rejection_reason || undefined;
  }

  const emailStatus = user.email_verified_at ? 'verified' : 'unverified';
  const phoneStatus = user.phone_verified_at ? 'verified' : 'unverified';

  // Determine fully verified
  // Booking eligibility requires verified email and approved KYC. Phone OTP is optional.
  const isFullyVerified = emailStatus === 'verified' && kyc === 'approved';

  return {
    email: emailStatus,
    phone: phoneStatus,
    kyc,
    ...(kycRejectionReason && { kyc_rejection_reason: kycRejectionReason }),
    is_fully_verified: isFullyVerified,
  };
}


async function sendPhoneVerificationSms(phone: string, code: string): Promise<boolean> {
  const authKey = process.env.MSG91_AUTH_KEY;
  const templateId = process.env.MSG91_TEMPLATE_ID;
  if (!authKey || !templateId) {
    console.error('[VERIFICATION:SMS] MSG91 configuration is incomplete.');
    return false;
  }
  try {
    const params = new URLSearchParams({
      template_id: templateId,
      mobile: `91${phone}`,
      otp: code,
      otp_length: '6',
      otp_expiry: '10',
    });
    const response = await fetch(`https://control.msg91.com/api/v5/otp?${params.toString()}`, {
      method: 'POST',
      headers: { authkey: authKey, 'Content-Type': 'application/json' },
    });
    const payload: any = await response.json().catch(() => ({}));
    return response.ok && (payload.type === 'success' || payload.type === 'SUCCESS' || Boolean(payload.request_id));
  } catch (error: any) {
    console.error('[VERIFICATION:SMS] MSG91 request failed:', error?.message || 'Unknown error');
    return false;
  }
}

async function invalidatePendingCode(supabase: any, key: string): Promise<void> {
  await supabase.from('verification_codes').update({ used_at: new Date().toISOString() }).eq('key', key).is('used_at', null);
}

// ========== Email Verification ==========

export async function requestEmailCode(req: Request, res: Response, next: NextFunction): Promise<void> {
  try {
    requestEmailCodeSchema.parse(req.body);
    const userId = req.user!.id;
    const supabase = getSupabase();

    const { data: user } = await supabase
      .from('users')
      .select('email, email_verified_at')
      .eq('id', userId)
      .single();

    if (!user) {
      throw NotFound('User not found.');
    }

    if (user.email_verified_at) {
      throw BadRequest('Email is already verified.');
    }

    const code = generateCode();
    const key = `email:${userId}`;
    await storeCode(supabase, key, code);
    const delivery = await emailService.sendVerificationEmail(user.email, code, 'email');
    if (!delivery.success) {
      await invalidatePendingCode(supabase, key);
      res.status(502).json({ message: 'Email delivery failed. Please try again later.' });
      return;
    }
    res.status(200).json({ message: 'Verification email accepted by the email provider.' });
  } catch (err) {
    next(err);
  }
}

export async function verifyEmail(req: Request, res: Response, next: NextFunction): Promise<void> {
  try {
    const input = verifyEmailCodeSchema.parse(req.body);
    const userId = req.user!.id;
    const supabase = getSupabase();

    const isValid = await verifyCode(supabase, `email:${userId}`, input.code);
    if (!isValid) {
      throw BadRequest('Invalid or expired verification code.');
    }

    const { error } = await supabase
      .from('users')
      .update({ email_verified_at: new Date().toISOString() })
      .eq('id', userId);

    if (error) throw error;

    // Also update profiles table for consistency
    await supabase
      .from('profiles')
      .update({ is_email_verified: true })
      .eq('user_id', userId);

    res.status(200).json({
      message: 'Email verified successfully.',
    });
  } catch (err) {
    next(err);
  }
}

// ========== Phone Verification ==========

export async function requestPhoneCode(req: Request, res: Response, next: NextFunction): Promise<void> {
  try {
    const input = requestPhoneCodeSchema.parse(req.body);
    const userId = req.user!.id;
    const supabase = getSupabase();
    const normalizedPhone = normalizeIndianPhone(input.phone);

    // Reject a number already assigned to another account before sending OTP.
    const { data: existingPhone, error: phoneLookupError } = await supabase
      .from('users')
      .select('id')
      .eq('phone', normalizedPhone)
      .neq('id', userId)
      .limit(1);

    if (phoneLookupError) throw phoneLookupError;
    if (existingPhone && existingPhone.length > 0) {
      throw BadRequest('This mobile number is already registered to another account.');
    }

    // Store only the canonical 10-digit Indian mobile number.
    const { error: updateError } = await supabase
      .from('users')
      .update({ phone: normalizedPhone })
      .eq('id', userId);

    if (updateError) {
      if (updateError.code === '23505') throw BadRequest('This phone number is already in use.');
      throw updateError;
    }

    const code = generateCode();
    const key = `phone:${userId}`;
    await storeCode(supabase, key, code);
    const sent = await sendPhoneVerificationSms(normalizedPhone, code);
    if (!sent) {
      await invalidatePendingCode(supabase, key);
      res.status(502).json({ message: 'SMS delivery failed. Please try again later.' });
      return;
    }
    res.status(200).json({ message: 'OTP request accepted by the SMS provider.' });
  } catch (err) {
    next(err);
  }
}

